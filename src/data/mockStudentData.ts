let nextStudentCounter = 135;

export const generateStudentCode = (): string => {
  const stuPrefix = getBusinessPrefix('studentReference');
  const code = `${stuPrefix}${String(nextStudentCounter).padStart(6, '0')}`;
  nextStudentCounter += 1;
  return code;
};

export const createStudentFromForm = (data: StudentFormData): StudentItem => {
  const stuIdPrefix = getInternalIdPrefix('student');
  const emergencyGuardian =
    data.guardians?.find((g) => g.isEmergencyContact) ||
    data.guardians?.find((g) => g.isPrimary) ||
    data.guardians?.[0];
  const emergencyName = emergencyGuardian
    ? [emergencyGuardian.firstName, emergencyGuardian.middleName, emergencyGuardian.lastName]
        .filter(Boolean)
        .join(' ')
        .trim() || `${emergencyGuardian.firstName || ''} ${emergencyGuardian.lastName || ''}`.trim()
    : undefined;
  const emergencyPhone = emergencyGuardian?.mobile || undefined;

  const newStudent: StudentItem = {
    id: `${stuIdPrefix}${Date.now()}`,
    studentCode: generateStudentCode(),
    admissionNumber: undefined, // Student creation does NOT assign admission number
    hasActiveAdmission: false, // Student creation does NOT create admission
    firstName: data.firstName.trim(),
    middleName: data.middleName.trim(),
    lastName: data.lastName.trim(),
    photoUrl: data.photoUrl,
    dateOfBirth: data.dateOfBirth,
    gender: (data.gender as any) || 'OTHER',
    bloodGroup: data.bloodGroup,
    specialCategory: data.specialCategory,
    specialCategoryDetails: data.specialCategoryDetails,
    nationality: data.nationality,
    religion: data.religion,
    category: data.category,
    motherTongue: data.motherTongue,
    placeOfBirth: data.placeOfBirth,
    governmentId: data.governmentId,
    mobile: data.mobile,
    alternateMobile: data.alternateMobile,
    email: data.email,
    emergencyContact: emergencyName,
    emergencyPhone: emergencyPhone,
    addressLine1: data.addressLine1,
    addressLine2: data.addressLine2,
    city: data.city,
    state: data.state,
    country: data.country,
    postalCode: data.postalCode,
    guardians: data.guardians || [],
    previousSchool: data.previousSchool,
    previousClass: data.previousClass,
    previousSchoolBoard: data.previousSchoolBoard,
    transferCertificateNumber: data.transferCertificateNumber,
    transferCertificateDate: data.transferCertificateDate,
    notes: data.notes,
    status: data.status,
    createdAt: new Date().toISOString(),
  };

  MOCK_STUDENTS.unshift(newStudent);
  return newStudent;
};

export const updateStudentInMock = (
  id: string,
  data: Partial<StudentItem>,
): StudentItem | undefined => {
  const index = MOCK_STUDENTS.findIndex((s) => s.id === id);
  if (index !== -1) {
    MOCK_STUDENTS[index] = {
      ...MOCK_STUDENTS[index],
      ...data,
    };
    return MOCK_STUDENTS[index];
  }
  return undefined;
};
